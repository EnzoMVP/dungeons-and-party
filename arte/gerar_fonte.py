COMPOSTOS = {
    "Á": ("A", "agudo"), "À": ("A", "grave"), "Â": ("A", "circunflexo"), "Ã": ("A", "til"),
    "É": ("E", "agudo"), "Ê": ("E", "circunflexo"), "Í": ("I", "agudo"),
    "Ó": ("O", "agudo"), "Ô": ("O", "circunflexo"), "Õ": ("O", "til"), "Ú": ("U", "agudo"),
}

# (nome, cor do glifo, cor da sombra ou None)
CORES = [
    ("claro", P.BRANCO, P.PRETO),
    ("dourado", P.AMARELO, P.PRETO),
    ("vermelho", P.LARANJA, P.PRETO),
    ("azul", P.CIANO, P.PRETO),
    ("verde", P.VERDE_CLARO, P.PRETO),
    ("escuro", P.PRETO, None),
]
ESCALAS = [2, 3, 5]


def mascara_do_caractere(ch):
    """Retorna matriz 5 x 10 (linhas 0..9) com True onde há tinta."""
    m = [[False] * 5 for _ in range(10)]

    def aplicar(linhas, y0):
        for dy, linha in enumerate(linhas):
            for dx, c in enumerate(linha):
                if c == "#":
                    m[y0 + dy][dx] = True

    if ch in COMPOSTOS:
        base, acento = COMPOSTOS[ch]
        aplicar(GLIFOS[base], TOPO_CORPO)
        aplicar(ACENTOS[acento], 0)
    elif ch == "Ç":
        aplicar(GLIFOS["C"], TOPO_CORPO)
        aplicar(["..##."], 9)
    else:
        aplicar(GLIFOS[ch], TOPO_CORPO)
    return m


def caracteres():
    return "".join(GLIFOS.keys()) + "".join(COMPOSTOS.keys()) + "Ç"


def gerar():
    chars = caracteres()
    for nome_cor, cor, sombra in CORES:
        tela = Tela(LARGURA_CELULA * len(chars), ALTURA_CELULA)
        for i, ch in enumerate(chars):
            m = mascara_do_caractere(ch)
            ox = i * LARGURA_CELULA
            if sombra:
                for y in range(10):
                    for x in range(5):
                        if m[y][x]:
                            tela.ponto(ox + x + 1, y + 1, sombra)
            for y in range(10):
                for x in range(5):
                    if m[y][x]:
                        tela.ponto(ox + x, y, cor)
        for escala in ESCALAS:
            tela.salvar(f"ui/fonte_{nome_cor}_{escala}.png", escala=escala)

    dados = {
        "caracteres": chars,
        "largura_celula": LARGURA_CELULA,
        "altura_celula": ALTURA_CELULA,
        "topo_corpo": TOPO_CORPO,
        "altura_corpo": 7,
    }
    caminho = os.path.join(PASTA_ARTE, "..", "dungeons_and_party", "data", "fonte.json")
    os.makedirs(os.path.dirname(caminho), exist_ok=True)
    with open(caminho, "w", encoding="utf-8") as f:
        json.dump(dados, f, ensure_ascii=False, indent=2)


if __name__ == "__main__":
    gerar()
